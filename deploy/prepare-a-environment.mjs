// Run as the existing cta operator on the verified GCE. Stage only; no routing.
import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {createRequire} from 'node:module';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const app=resolve(process.argv[2]),source=resolve(process.argv[3]);
assert.equal(app,'/home/cta/legal-harness-candidate-ddddafa');
assert.equal(source,'/opt/legal_harness/.env');
const require=createRequire(join(app,'package.json'));
const {parse}=require('dotenv'),previous=parse(readFileSync(source));
const state=join(app,'.runtime');mkdirSync(state,{recursive:true,mode:0o700});
const releaseFile=join(state,'upstream.json'),envFile=join(state,'candidate.env');
assert.ok(!existsSync(envFile),'Staged configuration already exists; verify it instead of overwriting');
const env={};
for(const key of ['TAXLAB_API_KEY','SUPABASE_URL','SUPABASE_PUBLISHABLE_KEY','SUPABASE_ANON_KEY','LAW_OC'])if(previous[key])env[key]=previous[key];
assert.ok(env.TAXLAB_API_KEY&&env.LAW_OC,'Existing authentication and law credentials required');
Object.assign(env,{PORT:'3100',HOST:'127.0.0.1',PUBLIC_ORIGIN:'https://law.taxlab.kr',LAW_API_PROTOCOL:'https',KOREAN_LAW_MCP_CONNECT_TIMEOUT_MS:'10000',KOREAN_LAW_MCP_TIMEOUT_MS:'45000',KOREAN_LAW_MCP_RELEASE_FILE:releaseFile,MCP_MAX_UPSTREAM_REQUESTS:'48',MCP_MAX_UPSTREAM_BODY_BYTES:'2097152',MCP_MAX_TOTAL_UPSTREAM_BODY_BYTES:'8388608',MCP_MAX_TOOL_RESPONSE_CHARS:'50000'});
for(const v of Object.values(env))assert.ok(!/[\x00-\x1f"\\]/.test(v),'Unsupported environment value encoding');
const text=Object.entries(env).map(([k,v])=>k+'='+JSON.stringify(v)).join('\n')+'\n';
assert.deepEqual(parse(text),env,'Environment must round-trip without altering credentials');
const {koreanLawOptionsFromEnv}=await import(pathToFileURL(join(app,'dist/koreanLawClient.js')));
const entrypoint=koreanLawOptionsFromEnv({}).server.args[0];
const upstream=JSON.parse(readFileSync(join(app,'node_modules/korean-law-mcp/package.json')));
assert.equal(upstream.version,'4.13.0');
writeFileSync(releaseFile,JSON.stringify({version:upstream.version,entrypoint},null,2)+'\n',{mode:0o600,flag:'wx'});
writeFileSync(envFile,text,{mode:0o600,flag:'wx'});
const safe={app,env_file:envFile,upstream_file:releaseFile,env_keys:Object.keys(env),server_only_db_key_present:false,github_key_present:false,port:3100,host:'127.0.0.1',upstream:upstream.version,env_sha256:createHash('sha256').update(text).digest('hex'),upstream_sha256:createHash('sha256').update(readFileSync(releaseFile)).digest('hex')};
writeFileSync(join(state,'staging-config.json'),JSON.stringify(safe,null,2));console.log(JSON.stringify(safe));
